// Browser acceptance for docs/specs/neighbors-top.md. No project dependency is added:
// resolve Playwright locally, or set PLAYWRIGHT_MODULE to an installed module path.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';

const args = process.argv.slice(2);
const option = (name, fallback) => {
  const i = args.indexOf(name);
  return i < 0 ? fallback : args[i + 1];
};
const fixturePath = option('--fixture');
assert(fixturePath, 'Pass --fixture <save.json>, generated by scripts/fixtures/neighbors-top.ts');
const fixture = JSON.parse(await readFile(resolve(fixturePath), 'utf8'));
assert(fixture.world.week >= 30, 'Acceptance needs a developed game, week 30+');
assert(fixture.world.players.some((player) => player.isBot && player.freedomWeek !== null), 'A neighbor must be free');
for (const player of fixture.world.players) {
  assert(fixture.history[player.id]?.length >= 2, `Missing progress history for ${player.id}`);
}
const output = resolve(option('--output', join(tmpdir(), 'archipelago-neighbors-top')));
const url = option('--url', 'http://127.0.0.1:5180');
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const channel = option('--channel', process.platform === 'win32' ? 'msedge' : undefined);
const browser = await chromium.launch({ headless: true, ...(channel ? { channel } : {}) });
await mkdir(output, { recursive: true });
const errors = [];
const consoleErrors = [];
const results = [];
const page = await browser.newPage();
page.on('pageerror', (error) => errors.push(error.message));
page.on('console', (msg) => {
  if (msg.type() === 'error') consoleErrors.push({ text: msg.text(), url: msg.location().url });
});

async function settle() {
  await page.evaluate(async () => {
    await document.fonts.ready;
    const card = document.querySelector('.neighbor-card');
    if (card) await Promise.all(card.getAnimations().map((animation) => animation.finished.catch(() => {})));
    await new Promise((done) => requestAnimationFrame(() => requestAnimationFrame(done)));
  });
}

async function load(longName = false) {
  const save = structuredClone(fixture);
  if (longName) save.world.players[0].islandName = 'Остров Солнечной Свободы';
  assert.equal('Остров Солнечной Свободы'.length, 24);
  await page.goto(url);
  await page.evaluate((data) => localStorage.setItem('archipelago.save.v1', JSON.stringify(data)), save);
  await page.reload();
  await page.locator('.hud').waitFor();
  await settle();
}

async function mobileSnapshot() {
  return page.evaluate(() => {
    const selectors = ['.hud', '.top', '.badge', '.badge-text', '.title', '.sub', '.emblem',
      '.nb-mini', '.nb-mini .ring-avatar', '.stats', '.stat', '.sheet', '.sheet-cta'];
    return Object.fromEntries(selectors.map((selector) => [selector,
      [...document.querySelectorAll(selector)].map((element) => {
        const r = element.getBoundingClientRect();
        const s = getComputedStyle(element);
        return {
          rect: [r.x, r.y, r.width, r.height].map((v) => Math.round(v * 10) / 10),
          display: s.display, padding: s.padding, gap: s.gap, font: s.font,
          borderRadius: s.borderRadius, overflow: s.overflow,
        };
      })]));
  });
}

async function geometry() {
  return page.evaluate(() => {
    const rect = (element) => {
      if (!element || !element.getClientRects().length || getComputedStyle(element).visibility === 'hidden') return null;
      const r = element.getBoundingClientRect();
      return { left: r.left, right: r.right, top: r.top, bottom: r.bottom, width: r.width, height: r.height };
    };
    const visible = (selector) => [...document.querySelectorAll(selector)].map(rect).filter(Boolean);
    const bar = visible('.nb-bar')[0];
    return {
      top: rect(document.querySelector('.top')), badge: rect(document.querySelector('.badge')),
      stats: rect(document.querySelector('.stats')), bar,
      mini: visible('.badge .nb-mini')[0], chips: visible(bar ? '.nb-bar .nb-chip' : '.badge .nb-mini .nb-chip'),
      left: rect(document.querySelector('.col-left')), right: rect(document.querySelector('.col-right')),
      card: rect(document.querySelector('.neighbor-card')), ticker: rect(document.querySelector('.ticker')),
      mode: document.querySelector('[data-neighbors-size]')?.getAttribute('data-neighbors-size'),
      oldRow: !!document.querySelector('.col-top'), overflow: document.documentElement.scrollWidth > innerWidth,
      viewport: { width: innerWidth, height: innerHeight },
    };
  });
}

function checkHeader(g) {
  assert(!g.oldRow, 'The obsolete .col-top row remains');
  assert(!g.overflow, 'Horizontal page overflow');
  assert(g.badge.right <= g.stats.left + 1, 'Badge overlaps financial stats');
  assert(Math.abs((g.badge.top + g.badge.bottom) / 2 - (g.stats.top + g.stats.bottom) / 2) <= 1,
    'Header wraps onto a second row');
  const strip = g.bar || g.mini;
  assert(strip, 'No visible neighbor strip');
  assert.equal(g.chips.length, 4, 'All four progress avatars must remain visible');
  if (g.bar) {
    assert(g.bar.left >= g.badge.right - 1, 'Neighbor strip overlaps badge');
    assert(g.bar.right <= g.stats.left + 1, 'Neighbor strip overlaps stats');
    assert(g.bar.bottom <= g.top.bottom + 1, 'Neighbor strip is below the header');
  } else {
    assert(g.mini.left >= g.badge.left && g.mini.right <= g.badge.right + 1, 'Fallback escapes badge');
  }
  for (const chip of g.chips) {
    assert(chip.left >= strip.left - 1 && chip.right <= strip.right + 1, 'A neighbor chip is clipped');
    assert(Math.abs(chip.top - g.chips[0].top) <= 1, 'Neighbor chips wrap');
  }
}

function checkOverlay(g, key) {
  const r = g[key];
  assert(r, `${key} is not visible`);
  assert(r.left >= g.left.right - 1 && r.right <= g.right.left + 1, `${key} overlaps a side column`);
  assert(r.left >= 0 && r.right <= g.viewport.width, `${key} escapes viewport horizontally`);
  assert(r.top >= g.top.bottom - 1 && r.bottom <= g.viewport.height + 1, `${key} escapes viewport vertically`);
}

async function neighborButton() {
  return page.locator('.nb-chip:not(.me):visible').first();
}

try {
  await page.setViewportSize({ width: 390, height: 844 });
  await load();
  const mobile = await mobileSnapshot();
  if (args.includes('--baseline')) {
    await writeFile(join(output, 'mobile-baseline.json'), JSON.stringify(mobile, null, 2));
    await page.screenshot({ path: join(output, 'mobile-before.png') });
    await (await neighborButton()).click();
    await page.locator('.neighbor-modal .neighbor-card').waitFor();
    await page.screenshot({ path: join(output, 'mobile-card-before.png') });
    console.log(`Mobile baseline saved to ${output}`);
  } else {
    const baselineDir = option('--baseline-dir');
    if (baselineDir) {
      const before = JSON.parse(await readFile(join(resolve(baselineDir), 'mobile-baseline.json'), 'utf8'));
      assert.deepEqual(mobile, before, 'Mobile geometry/styles changed');
    }
    await page.screenshot({ path: join(output, 'mobile-390x844.png') });
    await (await neighborButton()).click();
    await page.locator('.neighbor-modal .neighbor-card').waitFor();
    await page.screenshot({ path: join(output, 'mobile-card.png') });
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.neighbor-card').count(), 0);
    await load(true);
    await page.screenshot({ path: join(output, 'mobile-long-390x844.png') });

    for (const longName of [false, true]) {
      await load(longName);
      for (const [width, height] of [[1024, 768], [1280, 720], [1366, 768], [1440, 900], [1920, 1080]]) {
        await page.setViewportSize({ width, height });
        await settle();
        const g = await geometry();
        checkHeader(g);
        const name = `${longName ? 'long' : 'short'}-${width}x${height}`;
        await page.screenshot({ path: join(output, `${name}.png`) });
        await (await neighborButton()).click();
        await page.locator('.neighbor-card').waitFor();
        await settle();
        const open = await geometry();
        checkOverlay(open, 'card');
        assert.equal(open.top.height, g.top.height, 'Card shifts header height');
        // Clicking yourself must leave the selected neighbor alone.
        const self = page.locator('.nb-chip.me:visible').first();
        if (!(await self.isDisabled())) await self.click();
        assert.equal(await page.locator('.neighbor-card').count(), 1, 'Self click changes selection');
        assert.match(await (await neighborButton()).getAttribute('aria-label') || '', /\d+%/);
        assert.match(await (await neighborButton()).getAttribute('title') || '', /\d+%/);
        if (width === 1366 || width === 1920 || !g.bar) {
          await page.screenshot({ path: join(output, `${name}-card.png`) });
        }
        await (await neighborButton()).click();
        assert.equal(await page.locator('.neighbor-card').count(), 0, 'Repeat click does not close card');
        await (await neighborButton()).click();
        await page.locator('.neighbor-card .close').click();
        assert.equal(await page.locator('.neighbor-card').count(), 0, 'Cross does not close card');
        await (await neighborButton()).click();
        await page.keyboard.press('Escape');
        assert.equal(await page.locator('.neighbor-card').count(), 0, 'Escape does not close card');
        if (g.ticker) checkOverlay(g, 'ticker');
        results.push({ name, mode: g.mode, fallback: !g.bar, headerHeight: g.top.height, available: g.stats.left - g.badge.right });
      }
    }

    // Exercise the width observer at the same viewport after changing badge content.
    await page.setViewportSize({ width: 1366, height: 768 });
    await load();
    const initial = await geometry();
    await page.evaluate(async () => {
      const { useGame } = await import('/src/store.ts');
      const world = structuredClone(useGame.getState().world);
      world.players[0].islandName = 'Остров Солнечной Свободы';
      useGame.setState({ world });
    });
    await settle();
    checkHeader(await geometry());

    await page.getByRole('button', { name: /Следующая неделя/ }).click();
    await page.locator('.modal-backdrop').waitFor();
    await page.keyboard.press('Escape');
    await page.locator('.ticker').waitFor();
    await settle();
    const afterWeek = await geometry();
    checkHeader(afterWeek);
    checkOverlay(afterWeek, 'ticker');
    assert.equal(afterWeek.top.height, initial.top.height, 'News ticker shifts header height');
    await page.screenshot({ path: join(output, 'news-after-next-week.png') });
    assert.equal(errors.length, 0, `Browser runtime errors: ${errors.join('; ')}`);
    const relevantErrors = consoleErrors.filter((error) =>
      !(error.text.includes('ERR_CERT') && /fonts\.(googleapis|gstatic)\.com/.test(error.url)));
    assert.equal(relevantErrors.length, 0, `Browser console errors: ${JSON.stringify(relevantErrors)}`);
    await writeFile(join(output, 'results.json'), JSON.stringify({ results, errors, consoleErrors, mobileUnchanged: !!baselineDir }, null, 2));
    console.log(JSON.stringify({ output, results, mobileUnchanged: !!baselineDir, runtimeErrors: errors.length, consoleErrors: relevantErrors.length }, null, 2));
  }
} finally {
  await browser.close();
}
